"""## Import Libraries"""

import torch
import gradio as gr
from transformers import AutoTokenizer, AutoModelForTokenClassification, pipeline
import pandas as pd

"""## Load the Model and Tokenizer

We will use the model name `Babelscape/wikineural-multilingual-ner` to load its Tokenizer and Model from the HuggingFace Hub.
"""

model_name = "Babelscape/wikineural-multilingual-ner"

print("Loading model...")

tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForTokenClassification.from_pretrained(model_name)

print("Model loaded successfully ✅")

"""## Build the NER Pipeline


"""

device = 0 if torch.cuda.is_available() else -1

ner_pipeline = pipeline(
    "ner",
    model=model,
    tokenizer=tokenizer,
    aggregation_strategy="simple",
    device=device
)

print(f"Pipeline ready, running on: {'GPU' if device == 0 else 'CPU'}")

"""## Helper Function to Display Results Neatly

"""

def extract_entities(text):
    """
    Takes a text string, runs it through the NER model,
    and returns a DataFrame with the extracted entities,
    their type, and confidence score.
    """
    results = ner_pipeline(text)

    if not results:
        print("No entities were found in the text.")
        return pd.DataFrame(columns=["Entity", "Type", "Confidence"])

    df = pd.DataFrame([
        {
            "Entity": r["word"],
            "Type": r["entity_group"],
            "Confidence": round(float(r["score"]), 4)
        }
        for r in results
    ])
    return df

